const dictionaries: Record<Lang, Record<Key, string>> = { fr, en };

export type TKey = Key;
export type TFunction = (key: Key, params?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? fr[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}

export function useT(): { t: TFunction; lang: Lang } {
  const { lang } = useStore(settingsStore);
  const t = useCallback<TFunction>((key, params) => translate(lang, key, params), [lang]);
  return { t, lang };
}
